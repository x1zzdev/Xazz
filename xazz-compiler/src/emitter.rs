/// .xzz 파일을 독립 실행 가능한 Rust 소스 코드로 변환한다.
pub fn emit_rust(
    source_path: &str,
    out_path: Option<&str>,
) -> Result<(), Box<dyn std::error::Error>> {
    // ── Step 1: 소스 파일 읽기 ───────────────────────────────────────────────
    let source = fs::read_to_string(source_path)
        .map_err(|e| format!("IO 에러: 파일 읽기 실패 '{}' — {}", source_path, e))?;

    // ── Step 2: 렉서 ────────────────────────────────────────────────────────
    let mut lexer = Lexer::new(&source);
    let tokens = lexer.tokenize().map_err(|e| format!("{}", e))?;

    // ── Step 3: 파서 ────────────────────────────────────────────────────────
    let mut parser = Parser::new(tokens);
    let program = parser.parse().map_err(|e| format!("{}", e))?;

    // ── Step 4: 스키마 검증 + Rust 코드 생성 ────────────────────────────────
    let rust_code = generate_rust_src(&program, source_path)?;

    // ── Step 5: 출력 ────────────────────────────────────────────────────────
    match out_path {
        Some(path) => {
            fs::write(path, &rust_code)
                .map_err(|e| format!("IO 에러: 출력 파일 쓰기 실패 '{}' — {}", path, e))?;

            println!("✅  emit rust 완료 → {}", path);
            println!();
            println!("─── 실행 방법 ──────────────────────────────────────────────────");
            println!("  1) 새 Rust 프로젝트 생성:");
            println!("       cargo new my_analysis && cd my_analysis");
            println!("  2) Cargo.toml 에 의존성 추가:");
            println!(
                "       polars      = {{ version = \"0.53\", features = [\"lazy\", \"csv\"] }}"
            );
            println!("       encoding_rs = \"0.8\"");
            println!("  3) {} 를 src/main.rs 로 복사 후 실행:", path);
            println!("       cargo run");
            println!("────────────────────────────────────────────────────────────────");
        }
        None => println!("{}", rust_code),
    }

    Ok(())
}

// ─────────────────────────────────────────────────────────────────────────────
// ── 내부: AST → Rust 소스 문자열 생성 ─────────────────────────────────────────
// ─────────────────────────────────────────────────────────────────────────────

fn generate_rust_src(
    program: &Program,
    source_path: &str,
) -> Result<String, Box<dyn std::error::Error>> {
    // ── 전역 스키마 맵 구축 ──────────────────────────────────────────────────
    let mut schema_map: HashMap<String, Vec<StructField>> = HashMap::new();
    for stmt in &program.stmts {
        if let Stmt::TypeDecl { name, fields } = stmt {
            schema_map.insert(name.clone(), fields.clone());
        }
    }

    let mut out = String::new();

    // 파일 헤더
    out.push_str("// ═══════════════════════════════════════════════════════════════\n");
    out.push_str("// Auto-generated by xazzLang `emit rust`\n");
    out.push_str(&format!("// Source: {}\n", source_path));
    out.push_str("//\n");
    out.push_str("// [필요한 Cargo.toml 의존성]\n");
    out.push_str("//   polars      = { version = \"0.53\", features = [\"lazy\", \"csv\"] }\n");
    out.push_str("//   encoding_rs = \"0.8\"\n");
    if program_has_dl(program) {
        out.push_str("//   burn        = { version = \"0.21\", default-features = false, features = [\"std\", \"autodiff\"] }\n");
        out.push_str("//   burn-ndarray = { version = \"0.21\", default-features = false, features = [\"std\", \"burn-autodiff\"] }\n");
    }
    out.push_str("// ═══════════════════════════════════════════════════════════════\n\n");

    // 임포트
    out.push_str("use polars::prelude::*;\n");
    out.push_str("use encoding_rs::EUC_KR;\n");
    out.push_str("use std::io::Cursor;\n\n");

    if program_has_dl(program) {
        out.push_str(&emit_burn_imports());
        out.push('\n');
    }

    // CSV 로더 헬퍼
    out.push_str(&emit_csv_loader_fn());
    out.push('\n');

    // 딥러닝 (Burn) 모델 정의 + 학습 헬퍼
    if program_has_dl(program) {
        for stmt in &program.stmts {
            if let Stmt::ModelDecl { name, layers } = stmt {
                out.push_str(&emit_dl_model_struct(name, layers));
            }
        }
        out.push_str(&emit_extract_xy_fn());
        out.push('\n');
    }

    // fn main()
    out.push_str("fn main() -> Result<(), Box<dyn std::error::Error>> {\n");

    // TypeDecl → 스키마 주석 블록
    let has_schemas = program
        .stmts
        .iter()
        .any(|s| matches!(s, Stmt::TypeDecl { .. }));
    if has_schemas {
        out.push_str("    // ── xazzLang Schema Definitions (참조용 주석) ─────────────────────\n");
        for stmt in &program.stmts {
            if let Stmt::TypeDecl { name, fields } = stmt {
                out.push_str(&format!("    // type {} = {{\n", name));
                for f in fields {
                    out.push_str(&format!("    //   {:<14}: {}\n", f.name, f.field_type));
                }
                out.push_str("    // }\n");
            }
        }
        out.push_str(
            "    // ──────────────────────────────────────────────────────────────────\n\n",
        );
    }

    // 변수별 스키마 추적
    let mut var_col_types: HashMap<String, HashMap<String, String>> = HashMap::new();

    // VarDecl → LazyFrame 파이프라인
    for stmt in &program.stmts {
        if let Stmt::VarDecl {
            var_name,
            is_mut,
            source,
            ops,
        } = stmt
        {
            let mut_kw = if *is_mut { "mut " } else { "" };

            // 활성 컬럼 타입 맵 결정
            let col_types: HashMap<String, String> = match source {
                PipelineSource::Load { schema_name, .. } => schema_map
                    .get(schema_name)
                    .map(|fields| {
                        fields
                            .iter()
                            .map(|f| (f.name.clone(), f.field_type.clone()))
                            .collect()
                    })
                    .unwrap_or_default(),
                PipelineSource::VarRef(src_var) => var_col_types
                    .get(src_var.as_str())
                    .cloned()
                    .unwrap_or_default(),
            };

            // 스키마 검증
            if !col_types.is_empty() {
                for op in ops {
                    validate_op_columns(op, &col_types, &var_col_types, source_path)?;
                }
            }

            // 코드 생성 헤더
            out.push_str(&format!(
                "    // ── Pipeline: {}v {} ──────────────────────────────────────────\n",
                mut_kw, var_name
            ));

            // 소스 결정
            match source {
                PipelineSource::Load {
                    file_path,
                    schema_name,
                } => {
                    out.push_str(&format!(
                        "    // load(\"{}\") :: {}\n",
                        file_path, schema_name
                    ));
                    out.push_str(&format!(
                        "    let {}{} = load_csv(\"{}\")? // :: {}\n",
                        mut_kw, var_name, file_path, schema_name
                    ));
                    out.push_str("        .lazy()\n");
                }
                PipelineSource::VarRef(src_var) => {
                    out.push_str(&format!(
                        "    let {}{} = {}.clone().lazy()\n",
                        mut_kw, var_name, src_var
                    ));
                }
            }

            // ── 파이프라인 연산자 체이닝 ─────────────────────────────────────
            // GroupBy+agg 패턴: GroupBy를 저장해 두었다가 다음 집계 연산자와 합쳐 출력
            let mut has_count = false;
            let mut pending_group_col: Option<String> = None;

            for op in ops {
                match op {
                    PipelineOp::Filter(expr) => {
                        let polars_expr = to_typed_polars_expr(expr, &col_types);
                        out.push_str(&format!(
                            "        .filter({})  // |> filter({})\n",
                            polars_expr,
                            Codegen::expr_to_xzz(expr)
                        ));
                    }
                    PipelineOp::Select(cols) => {
                        let polars_cols: Vec<String> =
                            cols.iter().map(|c| format!("col(\"{}\")", c)).collect();
                        out.push_str(&format!(
                            "        .select([{}])  // |> select([{}])\n",
                            polars_cols.join(", "),
                            cols.join(", ")
                        ));
                    }
                    PipelineOp::Count(None) => {
                        // count (no arg): 행 수 출력용 플래그만 설정
                        has_count = true;
                    }

                    // ── GroupBy 저장 ───────────────────────────────────────────
                    PipelineOp::GroupBy(group_col) => {
                        pending_group_col = Some(group_col.clone());
                    }

                    // ── 집계 연산자: GroupBy와 함께 또는 단독 ─────────────────
                    PipelineOp::Count(Some(agg_col)) => {
                        if let Some(gc) = pending_group_col.take() {
                            out.push_str(&format!(
                                "        .group_by([col(\"{}\")])\n        .agg([col(\"{}\").count()])  // |> groupBy(\"{}\") |> count(\"{}\")\n",
                                gc, agg_col, gc, agg_col
                            ));
                        } else {
                            out.push_str(&format!(
                                "        .select([col(\"{}\").count()])  // |> count(\"{}\")\n",
                                agg_col, agg_col
                            ));
                        }
                    }
                    PipelineOp::Sum(agg_col) => {
                        if let Some(gc) = pending_group_col.take() {
                            out.push_str(&format!(
                                "        .group_by([col(\"{}\")])\n        .agg([col(\"{}\").sum()])  // |> groupBy(\"{}\") |> sum(\"{}\")\n",
                                gc, agg_col, gc, agg_col
                            ));
                        } else {
                            out.push_str(&format!(
                                "        .select([col(\"{}\").sum()])  // |> sum(\"{}\")\n",
                                agg_col, agg_col
                            ));
                        }
                    }
                    PipelineOp::Mean(agg_col) => {
                        if let Some(gc) = pending_group_col.take() {
                            out.push_str(&format!(
                                "        .group_by([col(\"{}\")])\n        .agg([col(\"{}\").mean()])  // |> groupBy(\"{}\") |> mean(\"{}\")\n",
                                gc, agg_col, gc, agg_col
                            ));
                        } else {
                            out.push_str(&format!(
                                "        .select([col(\"{}\").mean()])  // |> mean(\"{}\")\n",
                                agg_col, agg_col
                            ));
                        }
                    }
                    PipelineOp::Min(agg_col) => {
                        if let Some(gc) = pending_group_col.take() {
                            out.push_str(&format!(
                                "        .group_by([col(\"{}\")])\n        .agg([col(\"{}\").min()])  // |> groupBy(\"{}\") |> min(\"{}\")\n",
                                gc, agg_col, gc, agg_col
                            ));
                        } else {
                            out.push_str(&format!(
                                "        .select([col(\"{}\").min()])  // |> min(\"{}\")\n",
                                agg_col, agg_col
                            ));
                        }
                    }
                    PipelineOp::Max(agg_col) => {
                        if let Some(gc) = pending_group_col.take() {
                            out.push_str(&format!(
                                "        .group_by([col(\"{}\")])\n        .agg([col(\"{}\").max()])  // |> groupBy(\"{}\") |> max(\"{}\")\n",
                                gc, agg_col, gc, agg_col
                            ));
                        } else {
                            out.push_str(&format!(
                                "        .select([col(\"{}\").max()])  // |> max(\"{}\")\n",
                                agg_col, agg_col
                            ));
                        }
                    }

                    // ── 정렬 / 슬라이싱 ────────────────────────────────────────
                    PipelineOp::OrderBy {
                        col: sort_col,
                        desc,
                    } => {
                        out.push_str(&format!(
                            "        .sort([\"{}\"], SortMultipleOptions::default().with_order_descending({}))  // |> orderBy(\"{}\", desc: {})\n",
                            sort_col, desc, sort_col, desc
                        ));
                    }
                    PipelineOp::Take(n) => {
                        out.push_str(&format!("        .limit({})  // |> take({})\n", n, n));
                    }

                    // ── Null 처리 ──────────────────────────────────────────────
                    PipelineOp::DropNull(drop_col) => {
                        out.push_str(&format!(
                            "        .drop_nulls(Some(vec![col(\"{}\")]))  // |> dropNull(\"{}\")\n",
                            drop_col, drop_col
                        ));
                    }
                    PipelineOp::FillNull {
                        col: fill_col,
                        value,
                    } => {
                        let lit_str = match value {
                            FillNullValue::Mean => format!("col(\"{}\").mean()", fill_col),
                            FillNullValue::Median => format!("col(\"{}\").median()", fill_col),
                            FillNullValue::Zero => "lit(0)".to_string(),
                            FillNullValue::Int(n) => format!("lit({}i64)", n),
                            FillNullValue::Float(f) => format!("lit({}f64)", f),
                            FillNullValue::Str(s) => format!("lit(\"{}\")", s),
                        };
                        out.push_str(&format!(
                            "        .with_columns([col(\"{}\").fill_null({})])  // |> fillNull(\"{}\", ...)\n",
                            fill_col, lit_str, fill_col
                        ));
                    }

                    // ── v0.16+ / v0.21 Join ────────────────────────────────────
                    PipelineOp::Join {
                        other,
                        left_on,
                        right_on,
                        how,
                    } => {
                        let left_cols: Vec<String> =
                            left_on.iter().map(|k| format!("col(\"{}\")", k)).collect();
                        let right_cols: Vec<String> =
                            right_on.iter().map(|k| format!("col(\"{}\")", k)).collect();
                        out.push_str(&format!(
                            "        .join(\n            {}.clone().lazy(),\n            [{}],\n            [{}],\n            JoinArgs::new({}),\n        )  // |> join({}, left_on: {:?}, right_on: {:?})\n",
                            other,
                            left_cols.join(", "),
                            right_cols.join(", "),
                            how.as_polars_str(),
                            other,
                            left_on,
                            right_on
                        ));
                    }

                    // ── v0.16+ WithColumn ──────────────────────────────────────
                    PipelineOp::WithColumn {
                        name: col_name,
                        expr,
                    } => {
                        let polars_expr = to_typed_polars_expr(expr, &col_types);
                        out.push_str(&format!(
                            "        .with_columns([{}.alias(\"{}\")])  // |> withColumn(\"{}\", {})\n",
                            polars_expr,
                            col_name,
                            col_name,
                            Codegen::expr_to_xzz(expr)
                        ));
                    }

                    // ── Chart: emitter 미지원 (런타임에서만 처리) ──────────────
                    PipelineOp::Chart(config) => {
                        out.push_str(&format!(
                            "        // |> chart {{ type: {} }}  →  [xazz:chart] JSON 출력\n",
                            config.chart_type.as_str()
                        ));
                    }

                    // ── v0.20 Cast ─────────────────────────────────────────────
                    PipelineOp::Cast {
                        col: cast_col,
                        to_type,
                    } => {
                        let polars_type = match to_type.as_str() {
                            "float" => "DataType::Float64",
                            "int" => "DataType::Int64",
                            "str" => "DataType::String",
                            "bool" => "DataType::Boolean",
                            other => other,
                        };
                        out.push_str(&format!(
                            "        .with_columns([col(\"{}\").cast({})])  // |> cast(\"{}\", \"{}\")\n",
                            cast_col, polars_type, cast_col, to_type
                        ));
                    }

                    // ── Rename ─────────────────────────────────────────────────
                    PipelineOp::Rename { old_name, new_name } => {
                        out.push_str(&format!(
                            "        .rename([\"{}\"], [\"{}\"], false)  // |> rename(\"{}\", \"{}\")\n",
                            old_name, new_name, old_name, new_name
                        ));
                    }

                    // ── Replace ────────────────────────────────────────────────
                    PipelineOp::Replace {
                        col: rep_col,
                        from,
                        to,
                    } => {
                        out.push_str(&format!(
                            "        .with_columns([col(\"{}\").str().replace(lit(\"{}\"), lit(\"{}\"), false).alias(\"{}\")])  // |> replace(\"{}\", \"{}\", \"{}\")\n",
                            rep_col, from, to, rep_col, rep_col, from, to
                        ));
                    }

                    // ── v0.22 sample(n) / sample(n, seed: 42) ──────────────────
                    PipelineOp::Sample { n, seed } => match seed {
                        Some(s) => {
                            out.push_str(&format!(
                                "        .collect()?.sample_n_literal({}, false, false, Some({}))?.lazy()  // |> sample({}, seed: {})\n",
                                n, s, n, s
                            ));
                        }
                        None => {
                            out.push_str(&format!(
                                "        .collect()?.sample_n_literal({}, false, false, None)?.lazy()  // |> sample({})\n",
                                n, n
                            ));
                        }
                    },

                    // ── v0.22 median / variance / std 집계 ─────────────────────
                    PipelineOp::Median(agg_col) => {
                        if let Some(gc) = pending_group_col.take() {
                            out.push_str(&format!(
                                "        .group_by([col(\"{}\")])\n        .agg([col(\"{}\").median()])  // |> groupBy(\"{}\") |> median(\"{}\")\n",
                                gc, agg_col, gc, agg_col
                            ));
                        } else {
                            out.push_str(&format!(
                                "        .select([col(\"{}\").median()])  // |> median(\"{}\")\n",
                                agg_col, agg_col
                            ));
                        }
                    }
                    PipelineOp::Variance(agg_col) => {
                        if let Some(gc) = pending_group_col.take() {
                            out.push_str(&format!(
                                "        .group_by([col(\"{}\")])\n        .agg([col(\"{}\").var(1)])  // |> groupBy(\"{}\") |> variance(\"{}\")\n",
                                gc, agg_col, gc, agg_col
                            ));
                        } else {
                            out.push_str(&format!(
                                "        .select([col(\"{}\").var(1)])  // |> variance(\"{}\")\n",
                                agg_col, agg_col
                            ));
                        }
                    }
                    PipelineOp::Std(agg_col) => {
                        if let Some(gc) = pending_group_col.take() {
                            out.push_str(&format!(
                                "        .group_by([col(\"{}\")])\n        .agg([col(\"{}\").std(1)])  // |> groupBy(\"{}\") |> std(\"{}\")\n",
                                gc, agg_col, gc, agg_col
                            ));
                        } else {
                            out.push_str(&format!(
                                "        .select([col(\"{}\").std(1)])  // |> std(\"{}\")\n",
                                agg_col, agg_col
                            ));
                        }
                    }
                    // ── v0.5 딥러닝 연산자: emit rust 에서는 런타임 학습/예측으로 안내 ──
                    PipelineOp::Train { model_name, config } => {
                        out.push_str(&format!(
                            "        // |> train({}, target: \"{}\", epochs: {})  → xazz 실행 시 Burn 학습 수행\n",
                            model_name, config.target, config.epochs
                        ));
                    }
                    PipelineOp::Predict { model_var, as_col } => {
                        let as_str = as_col
                            .as_deref()
                            .map(|c| format!(", as: \"{}\"", c))
                            .unwrap_or_default();
                        out.push_str(&format!(
                            "        // |> predict({}{})  → 예측 컬럼 추가 (xazz 실행 시)\n",
                            model_var, as_str
                        ));
                    }
                    // ── v0.6 withDp — emit rust 에서는 런타임 DP 주입으로 안내 ──
                    PipelineOp::WithDp(args) => {
                        out.push_str(&format!(
                            "        // |> withDp(epsilon: {}, mechanism: {})  → xazz 실행 시 DP 노이즈 주입\n",
                            args.epsilon,
                            args.mechanism.as_str()
                        ));
                    }
                }
            }

            // collect
            out.push_str("        .collect()?;\n");

            // 결과 출력
            if has_count {
                out.push_str(&format!(
                    "    println!(\"[{}] count = {{}}\", {}.height());\n",
                    var_name, var_name
                ));
            } else {
                out.push_str(&format!(
                    "    println!(\"[{}]\\n{{}}\", {});\n",
                    var_name, var_name
                ));
            }
            out.push('\n');

            if !col_types.is_empty() {
                var_col_types.insert(var_name.clone(), col_types);
            }
        }
    }

    // 딥러닝 (Burn) 학습 문 실행
    for stmt in &program.stmts {
        if let Stmt::TrainStmt {
            source_var,
            model_name,
            config,
        } = stmt
        {
            out.push_str(&emit_dl_train_call(source_var, model_name, config));
        }
    }

    out.push_str("    Ok(())\n");
    out.push_str("}\n");

    Ok(out)
}

