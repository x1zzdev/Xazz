/// 스크립트에 DL 구문(ModelDecl / TrainStmt)이 포함되어 있는지 확인한다.
fn program_has_dl(program: &Program) -> bool {
    program
        .stmts
        .iter()
        .any(|s| matches!(s, Stmt::ModelDecl { .. } | Stmt::TrainStmt { .. }))
}

